    ADD COLUMN IF NOT EXISTS description VARCHAR(500);

ALTER TABLE bill_splits
    ADD COLUMN IF NOT EXISTS bill_date DATE;

CREATE TABLE IF NOT EXISTS bill_split_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_split_id BIGINT NOT NULL,
    item_name VARCHAR(150) NOT NULL,
    quantity DECIMAL(15, 3) NOT NULL,
    unit_price DECIMAL(15, 2) NOT NULL,
    amount DECIMAL(15, 2) NOT NULL,
    CONSTRAINT fk_bill_split_items_split
        FOREIGN KEY (bill_split_id) REFERENCES bill_splits (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);

CREATE TABLE IF NOT EXISTS bill_split_item_participants (
    item_id BIGINT NOT NULL,
    participant_id BIGINT NOT NULL,
    PRIMARY KEY (item_id, participant_id),
    CONSTRAINT fk_bill_split_item_participants_item
        FOREIGN KEY (item_id) REFERENCES bill_split_items (id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_bill_split_item_participants_participant
        FOREIGN KEY (participant_id)
        REFERENCES bill_split_participants (id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);
