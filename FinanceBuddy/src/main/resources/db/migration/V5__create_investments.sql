CREATE TABLE IF NOT EXISTS investments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    investment_name VARCHAR(150) NOT NULL,
    investment_type VARCHAR(20) NOT NULL,
    invested_amount DECIMAL(15, 2) NOT NULL,
    current_value DECIMAL(15, 2) NOT NULL,
    investment_date DATE NOT NULL,
    expected_return DECIMAL(5, 2) NOT NULL,
    risk_level VARCHAR(10) NOT NULL,
    notes VARCHAR(1000),
    created_at TIMESTAMP(6) NOT NULL,
    updated_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_investments_user
        FOREIGN KEY (user_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_investments_user_date
    ON investments (user_id, investment_date);

CREATE INDEX IF NOT EXISTS idx_investments_user_type
    ON investments (user_id, investment_type);
